def etim_archive() -> Path | None:
    if not ETIM_DIR.exists():
        return None
    extracted = ETIM_DIR / "extracted"
    if (extracted / "ETIMARTCLASS.csv").exists():
        return extracted
    archives = sorted(p for p in ETIM_DIR.glob("*.zip") if not p.name.startswith("_"))
    return archives[0] if archives else None


