def _grid(page, cols: list[float], rows: list[float]) -> None:
    for x in cols:
        page.draw_line((x, rows[0]), (x, rows[-1]))
    for y in rows:
        page.draw_line((cols[0], y), (cols[-1], y))


@pytest.fixture
def ordering_table_pdf(tmp_path: Path) -> Path:
    """A ruled ordering table: Type / Rated current / Packing unit / Weight."""
    document = pymupdf.open()
    page = document.new_page(width=460, height=300)
    cols = [30, 130, 240, 350, 440]
    rows = [60, 92, 124, 156]
    _grid(page, cols, rows)
    table = [
        ["Type", "Rated current I n A", "Packing unit PCS", "Weight 1 PC kg"],
        ["AX-10", "10", "5", "0.125"],
        ["AX-16", "16", "5", "0.125"],
    ]
    for r, row in enumerate(table):
        for c, value in enumerate(row):
            page.insert_text((cols[c] + 4, rows[r] + 18), value, fontsize=8)
    path = tmp_path / "ordering.pdf"
    document.save(path)
    return path


@pytest.fixture
def merged_cell_pdf(tmp_path: Path) -> Path:
    """A pole-count column stated once for a block of three rows -- merged by geometry."""
    document = pymupdf.open()
    page = document.new_page(width=460, height=300)
    cols = [30, 130, 250, 440]
    rows = [60, 92, 124, 156]
    # The pole column's vertical rules stop after the header, so the cell spans the block.
    for y in rows:
        page.draw_line((cols[0], y), (cols[-1], y)) if y in (rows[0], rows[1], rows[-1]) else page.draw_line((cols[1], y), (cols[-1], y))
    page.draw_line((cols[0], rows[0]), (cols[0], rows[-1]))
    page.draw_line((cols[1], rows[0]), (cols[1], rows[-1]))
    page.draw_line((cols[2], rows[0]), (cols[2], rows[-1]))
    page.draw_line((cols[3], rows[0]), (cols[3], rows[-1]))

    page.insert_text((cols[0] + 4, rows[0] + 18), "Number of poles", fontsize=7)
    page.insert_text((cols[1] + 4, rows[0] + 18), "Type", fontsize=7)
    page.insert_text((cols[2] + 4, rows[0] + 18), "Rated current I n A", fontsize=7)
    page.insert_text((cols[0] + 4, rows[1] + 18), "1", fontsize=8)
    for index, (sku, current) in enumerate((("AX-10", "10"), ("AX-16", "16"))):
        y = rows[1 + index]
        page.insert_text((cols[1] + 4, y + 18), sku, fontsize=8)
        page.insert_text((cols[2] + 4, y + 18), current, fontsize=8)
    path = tmp_path / "merged.pdf"
    document.save(path)
    return path


