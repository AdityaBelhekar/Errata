"""Fixtures for the R1 tests.

**The PDFs are built here rather than committed.** ``.gitignore`` excludes ``*.pdf`` (FR-9.5:
distribute URLs and hashes, never payloads), so a test that depended on a committed datasheet would
pass on the author's machine and fail on a clean clone -- the exact failure mode this repository
has already been careful about elsewhere. Every fixture below is generated by PyMuPDF at test time
from a literal description, which also means each one exercises a *named* document shape:

* ``ordering_table_pdf`` -- the well-formed case: a ruled table with a type column.
* ``merged_cell_pdf`` -- one cell spanning a block of rows, the ABB S200 pole-count shape.
* ``two_column_pdf`` -- two products side by side, the FR-1.6 bleed case.
* ``scanned_pdf`` -- a page with no text layer at all.

The real ABB datasheets are used where a test genuinely needs a real document, and those tests
**skip** when the corpus has not been fetched rather than failing.
"""

